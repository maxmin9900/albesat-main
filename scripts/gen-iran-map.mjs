// Reads scripts/iran.geo.json and emits src/lib/iran-map.ts with an accurate
// SVG path + city coordinates projected into the SAME space (so pins align).
import { readFile, writeFile } from "node:fs/promises";

const TARGET_W = 1000;

// City geo coordinates [lon, lat]
const CITIES = [
  { key: "tabriz", en: "Tabriz", lon: 46.2919, lat: 38.08 },
  { key: "heriz", en: "Heriz", lon: 47.1333, lat: 38.245 },
  { key: "qom", en: "Qom", lon: 50.8764, lat: 34.6401 },
  { key: "kashan", en: "Kashan", lon: 51.41, lat: 33.985 },
  { key: "isfahan", en: "Isfahan", lon: 51.6776, lat: 32.6539 },
  { key: "nain", en: "Nain", lon: 53.09, lat: 32.86 },
];

function collectPolygons(geo) {
  const feats =
    geo.type === "FeatureCollection"
      ? geo.features
      : geo.type === "Feature"
      ? [geo]
      : [{ geometry: geo }];
  const polys = [];
  for (const f of feats) {
    const g = f.geometry;
    if (!g) continue;
    if (g.type === "Polygon") polys.push(...g.coordinates);
    else if (g.type === "MultiPolygon")
      for (const p of g.coordinates) polys.push(...p);
  }
  return polys; // array of rings (array of [lon,lat])
}

async function main() {
  const geo = JSON.parse(await readFile("scripts/iran.geo.json", "utf8"));
  const rings = collectPolygons(geo);

  // bounds
  let minLon = Infinity,
    maxLon = -Infinity,
    minLat = Infinity,
    maxLat = -Infinity;
  for (const ring of rings)
    for (const [lon, lat] of ring) {
      if (lon < minLon) minLon = lon;
      if (lon > maxLon) maxLon = lon;
      if (lat < minLat) minLat = lat;
      if (lat > maxLat) maxLat = lat;
    }

  const midLat = (minLat + maxLat) / 2;
  const k = Math.cos((midLat * Math.PI) / 180);
  const rawW = (maxLon - minLon) * k;
  const rawH = maxLat - minLat;
  const scale = TARGET_W / rawW;
  const H = +(rawH * scale).toFixed(1);

  const project = (lon, lat) => [
    +(((lon - minLon) * k) * scale).toFixed(1),
    +(((maxLat - lat) * scale)).toFixed(1),
  ];

  // Build path (skip tiny islands to keep it clean)
  let d = "";
  for (const ring of rings) {
    if (ring.length < 12) continue; // drop tiny islands
    let sub = "";
    ring.forEach(([lon, lat], i) => {
      const [x, y] = project(lon, lat);
      sub += (i === 0 ? "M" : "L") + x + " " + y + " ";
    });
    d += sub + "Z ";
  }
  d = d.trim();

  const cityPoints = CITIES.map((c) => {
    const [x, y] = project(c.lon, c.lat);
    return { key: c.key, en: c.en, x, y };
  });

  const out = `// AUTO-GENERATED by scripts/gen-iran-map.mjs — accurate Iran outline
// viewBox: 0 0 ${TARGET_W} ${H}
export const IRAN_VIEWBOX = "0 0 ${TARGET_W} ${H}";
export const IRAN_W = ${TARGET_W};
export const IRAN_H = ${H};
export const IRAN_PATH = ${JSON.stringify(d)};
export const CITY_POINTS: { key: string; en: string; x: number; y: number }[] = ${JSON.stringify(
    cityPoints
  )};
`;

  await writeFile("src/lib/iran-map.ts", out);
  console.log(`✅ src/lib/iran-map.ts  viewBox 0 0 ${TARGET_W} ${H}`);
  console.log(`   path points ≈ ${(d.match(/[ML]/g) || []).length}`);
  console.log("   cities:", cityPoints.map((c) => `${c.en}(${c.x},${c.y})`).join(" "));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
